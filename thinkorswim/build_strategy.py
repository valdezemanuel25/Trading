#!/usr/bin/env python3
"""Build JournalTriggersStrategy.ts (a ToS Strategy for backtesting) from the JournalTriggers.ts study.

The study already tracks one trade at a time (enter at the signal candle's close, exit at T1, the stop,
or a time-out). The strategy reuses that tracker and adds AddOrder() calls so ToS can produce a
Strategy Report. Re-run this after changing the study:  python3 thinkorswim/build_strategy.py
"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
src = (here / "JournalTriggers.ts").read_text()

header = """# Journal Triggers STRATEGY - backtest version of JournalTriggers.ts (generated by build_strategy.py, do not edit by hand)
#
# Same signals and the same one-trade-at-a-time tracking as the study:
#   entry  = close of the signal candle
#   exit   = T1 (target), the stop, or a time-out (maxHoldBars or end of RTH) at that candle's close
# Right-click the chart -> Strategies -> Show Report for the trade list and P/L.
# vaSource defaults to VWAP_STATIC here so past trades only use information that existed at the time.
# Fills are idealised: targets and stops fill exactly at their price (no slippage, gaps fill at the stop).
"""

# Drop the study's header comment block (everything before 'declare upper;')
body = src[src.index("declare upper;"):]

# Backtest defaults: non-repainting value area, no alerts
body = body.replace("input vaSource = {default PROFILE, VWAP_STATIC};",
                    "input vaSource = {PROFILE, default VWAP_STATIC};", 1)
assert "default VWAP_STATIC" in body
body = re.sub(r"^Alert\(.*\n", "", body, flags=re.M)
body = body.replace("input showGateFunnel = no;", "input showGateFunnel = yes;", 1)
assert "input showGateFunnel = yes;" in body
body = body.replace("# Alerts fire on the first tick of the bar AFTER the signal candle closes\n", "")

orders = """
# ===== Strategy orders (backtest)
input tradeSize = 1;

# Entries: one per setup so the report shows which setup each trade came from
AddOrder(OrderType.BUY_TO_OPEN, openedNow and sigType == 3, close, tradeSize, Color.GREEN, Color.GREEN, "Sweep L");
AddOrder(OrderType.BUY_TO_OPEN, openedNow and sigType == 4, close, tradeSize, Color.CYAN, Color.CYAN, "POC L");
AddOrder(OrderType.BUY_TO_OPEN, openedNow and sigType == 6, close, tradeSize, Color.LIME, Color.LIME, "VAL flip L");
AddOrder(OrderType.BUY_TO_OPEN, openedNow and sigType == 8, close, tradeSize, Color.MAGENTA, Color.MAGENTA, "HTF L");
AddOrder(OrderType.BUY_TO_OPEN, openedNow and sigType == 10, close, tradeSize, Color.VIOLET, Color.VIOLET, "Fail BO L");
AddOrder(OrderType.BUY_TO_OPEN, openedNow and sigType == 12, close, tradeSize, Color.PINK, Color.PINK, "BB fail L");
AddOrder(OrderType.SELL_TO_OPEN, openedNow and sigType == 1, close, tradeSize, Color.RED, Color.RED, "Sweep S");
AddOrder(OrderType.SELL_TO_OPEN, openedNow and sigType == 2, close, tradeSize, Color.DARK_RED, Color.DARK_RED, "POC S");
AddOrder(OrderType.SELL_TO_OPEN, openedNow and sigType == 5, close, tradeSize, Color.ORANGE, Color.ORANGE, "VAH flip S");
AddOrder(OrderType.SELL_TO_OPEN, openedNow and sigType == 7, close, tradeSize, Color.MAGENTA, Color.MAGENTA, "HTF S");
AddOrder(OrderType.SELL_TO_OPEN, openedNow and sigType == 9, close, tradeSize, Color.VIOLET, Color.VIOLET, "Fail BO S");
AddOrder(OrderType.SELL_TO_OPEN, openedNow and sigType == 11, close, tradeSize, Color.PINK, Color.PINK, "BB fail S");

# Exits: the tracker resolves a trade on the candle AFTER entry or later, using last candle's target/stop
AddOrder(OrderType.SELL_TO_CLOSE, isWin and oDir[1] > 0, oTgt[1], tradeSize, Color.GREEN, Color.GREEN, "T1");
AddOrder(OrderType.SELL_TO_CLOSE, isLoss and oDir[1] > 0, oStp[1], tradeSize, Color.RED, Color.RED, "Stop");
AddOrder(OrderType.SELL_TO_CLOSE, isScratch and oDir[1] > 0, close, tradeSize, Color.GRAY, Color.GRAY, "Time");
AddOrder(OrderType.BUY_TO_CLOSE, isWin and oDir[1] < 0, oTgt[1], tradeSize, Color.GREEN, Color.GREEN, "T1");
AddOrder(OrderType.BUY_TO_CLOSE, isLoss and oDir[1] < 0, oStp[1], tradeSize, Color.RED, Color.RED, "Stop");
AddOrder(OrderType.BUY_TO_CLOSE, isScratch and oDir[1] < 0, close, tradeSize, Color.GRAY, Color.GRAY, "Time");

AddLabel(yes, "BACKTEST | levels: " + (if staticVA then "VWAP_STATIC (honest)" else "PROFILE (optimistic)") + " | trend " + (if useTrendFilter then "ON" else "off") + " | band walk " + (if useBandWalk then "ON" else "off") + " | magnet " + (if useMagnetCheck then "ON" else "off") + " | front-run " + (if useFrontRun then "ON" else "off") + " | strict " + (if useStrictTrigger then "ON" else "off") + " | 1-dir " + (if useOneDirection then "ON" else "off") + " | " + tradeSize + " contract(s)", Color.WHITE);
"""

out = header + "\n" + body.rstrip() + "\n" + orders
(here / "JournalTriggersStrategy.ts").write_text(out)
print("wrote", here / "JournalTriggersStrategy.ts", len(out.splitlines()), "lines")
