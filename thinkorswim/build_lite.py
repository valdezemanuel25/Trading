#!/usr/bin/env python3
"""Build JournalTriggersLite.ts: the same signal logic as JournalTriggers.ts with a minimal display.

Kept: signal arrows, alerts, the chop shading, one compact bubble per signal ("SWEEP S  T1 x  S y") and one
status label. Removed: every other bubble and label, gray ghost notes, level lines, T2 line, outcome dots.
vaSource defaults to VWAP_STATIC so live signals match the backtested strategy.
Re-run after changing the study:  python3 thinkorswim/build_lite.py
"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
src = (here / "JournalTriggers.ts").read_text()

header = """# Journal Triggers LITE - same signals as JournalTriggers.ts / JournalTriggersStrategy.ts, minimal display
# (generated by build_lite.py, do not edit by hand). Use on a /ES 5-minute chart with extended hours on.
# Arrows = signals. Bubble = setup, side, T1, stop. Label = HTF bias, chop and HTF-zone warnings.
"""

body = src[src.index("declare upper;"):]


def drop_calls(text, name):
    """Remove every top-level `name(...);` statement (they can span several lines)."""
    out, i = [], 0
    while True:
        j = text.find(name + "(", i)
        if j == -1:
            out.append(text[i:])
            return "".join(out)
        # only statements that start a line
        if j > 0 and text[j - 1] != "\n":
            out.append(text[i:j + len(name)])
            i = j + len(name)
            continue
        out.append(text[i:j])
        depth, k = 0, j
        while True:
            c = text[k]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        end = text.index(";", k) + 1
        if end < len(text) and text[end] == "\n":
            end += 1
        i = end


body = drop_calls(body, "AddChartBubble")
body = drop_calls(body, "AddLabel")

# Display defaults: lines, ghosts, T2 line and outcome dots off; live signals match the backtest
for old, new in [
    ("input vaSource = {default PROFILE, VWAP_STATIC};", "input vaSource = {PROFILE, default VWAP_STATIC};"),
    ("input showKeyLevels = yes;", "input showKeyLevels = no;"),
    ("input showHtfLines = yes;", "input showHtfLines = no;"),
    ("input showGhosts = yes;", "input showGhosts = no;"),
    ("input showOutcomes = yes;", "input showOutcomes = no;"),
    ("input showT2Line = yes;", "input showT2Line = no;"),
]:
    assert body.count(old) == 1, old
    body = body.replace(old, new)

lite = """
# ===== Lite display
input showBubbles = yes;
def nameS = if htfShort then 1 else if fboShort then 2 else if bbfShort then 3 else if flipShort then 4 else if sweepShort then 5 else 6;
def nameL = if htfLong then 1 else if fboLong then 2 else if bbfLong then 3 else if flipLong then 4 else if sweepLong then 5 else 6;
def stpS = if htfShort then hsStop else if fboShort then fbsStop else if bbfShort then xsStop else if flipShort then fsStop else if sweepShort then sStop else rsStop;
def stpL = if htfLong then hlStop else if fboLong then fblStop else if bbfLong then xlStop else if flipLong then flStop else if sweepLong then lStop else rlStop;

AddChartBubble(showBubbles and shownS and done, high,
    (if nameS == 1 then "HTF" else if nameS == 2 then "FAIL BO" else if nameS == 3 then "BB FAIL" else if nameS == 4 then "VAH FLIP" else if nameS == 5 then "SWEEP" else "POC") +
    " SHORT\\nT1 " + AsPrice(RT(close - t1DS)) + "  S " + AsPrice(RT(stpS)), Color.RED, yes);
AddChartBubble(showBubbles and shownL and done, low,
    (if nameL == 1 then "HTF" else if nameL == 2 then "FAIL BO" else if nameL == 3 then "BB FAIL" else if nameL == 4 then "VAL FLIP" else if nameL == 5 then "SWEEP" else "POC") +
    " LONG\\nT1 " + AsPrice(RT(close + t1DL)) + "  S " + AsPrice(RT(stpL)), Color.GREEN, no);

AddLabel(yes, "HTF " + (if htfBear then "BEAR" else if htfBull then "BULL" else "MIXED") +
    (if isChop then " | CHOP - wait" else "") +
    (if zSel == 3 then " | at 4h SMA200" else if zSel == 2 then " | at 4h SMA21" else if zSel == 1 then " | at 1h SMA50" else ""),
    if isChop then Color.ORANGE else if htfBear then Color.LIGHT_RED else if htfBull then Color.LIGHT_GREEN else Color.GRAY);
"""

out = header + "\n" + body.rstrip() + "\n" + lite
assert not re.search(r"[^\x00-\x7F]", out)
(here / "JournalTriggersLite.ts").write_text(out)
print("wrote", here / "JournalTriggersLite.ts", len(out.splitlines()), "lines")
